fn cmd(
    id: &'static str,
    title: &'static str,
    description: &'static str,
    group: &'static str,
    default_key: Option<&'static str>,
    contexts: Vec<CommandContext>,
) -> CommandSpec {
    CommandSpec {
        id: CommandId::from_static(id),
        title: Cow::Borrowed(title),
        description: Cow::Borrowed(description),
        group: Cow::Borrowed(group),
        default_key: default_key.map(Cow::Borrowed),
        contexts,
    }
}
